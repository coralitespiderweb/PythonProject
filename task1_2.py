# Day 2: Solve Math Mysteries to Power Your Spaceship
# Mission: Use input() to fuel your ship with a number, then print 5 math problems!
# The Galaxy Engine needs precise calculations to warp through star systems.
# Example: num = int(input("Enter a number: "))  # Converts your input to a number
