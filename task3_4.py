# Day 4: Mix Words and Numbers Like a Stellar Alchemist
# Mission: Use input() to conjure a space word, then mix it with words and numbers!
# Combine strings and numbers to craft cosmic spells in the Code Nebula.
word = input("Enter a space word (like 'Star'): ")  # Type a word to spark magic!
print(f"{word}ship")  # Example: Star + ship = Starship
print(f"Hello + World = {'Hello' + 'World'}")  # f-string blends words into HelloWorld
print(f"5 + 3 = {5 + 3}")  # Numbers align perfectly in the galaxy
# Try: print(f"Galaxy + 42 = Galaxy42")  # Error! A cosmic glitch!
print(f"Galaxy + 42 = {'Galaxy' + str(42)}")  # Fixed with str() to save the day
